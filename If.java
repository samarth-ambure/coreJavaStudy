public class If {
    public static void main(String[] args) {
        int playerAge = 9;

        System.out.println("Checking age for the ride...");

        // The condition inside ( ) must be true to run the code inside { }
        if (playerAge >= 10) {
            System.out.println("Access granted: Enjoy the roller coaster! 🎢");
        }

        System.out.println("Ride check complete.");
    }
}
